@pytest.mark.parametrize(
    "case",
    [
        "malformed preference",
        "top-level agents_dir",
        "site key",
        "unknown key",
        "unmarked configs",
        "top-level stray",
        "nested directory",
        "non-TOML file",
    ],
)
def test_config_side_failures_are_non_mutating(deploy_root, tmp_path, monkeypatch, case):
    config = _config_with_pref(tmp_path)
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path))
    deploy(deploy_root.path)
    prefs = config / "prefs" / "default.toml"
    configs = config / "configs"
    if case == "malformed preference":
        prefs.write_text("not = [valid\n", encoding="utf-8")
    elif case == "top-level agents_dir":
        prefs.write_text('agents_dir = "forbidden"\n', encoding="utf-8")
    elif case == "site key":
        prefs.write_text('[claude]\nauth = "token"\n', encoding="utf-8")
    elif case == "unknown key":
        prefs.write_text('model = "x"\n', encoding="utf-8")
    elif case == "unmarked configs":
        (configs / DEPLOY_MARKER_NAME).unlink()
    elif case == "top-level stray":
        (configs / "notes.txt").write_text("keep\n", encoding="utf-8")
    elif case == "nested directory":
        (configs / "first" / "nested").mkdir()
    else:
        (configs / "first" / "notes.txt").write_text("keep\n", encoding="utf-8")
    before = _tree(config)

    with pytest.raises(AgentGenError):
        deploy(deploy_root.path)
    assert _tree(config) == before


