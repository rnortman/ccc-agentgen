def test_switcher_behavior_and_completion(tmp_path, bash_runner):
    configs = tmp_path / "ccc" / "configs"
    (configs / "single").mkdir(parents=True)
    (configs / "single" / "only.toml").write_text("", encoding="utf-8")
    (configs / "multi").mkdir()
    for name in ("a.toml", "b space.toml"):
        (configs / "multi" / name).write_text("", encoding="utf-8")
    script = Path(__file__).parents[1] / "shell" / "ccc-env.sh"
    source = f"source {shlex.quote(str(script))}"
    env = os.environ | {"XDG_CONFIG_HOME": str(tmp_path)}
    only = shlex.quote(str(configs / "single" / "only.toml"))
    command = f"""
set -e
{source}
err=$(mktemp)
trap 'rm -f "$err"' EXIT
fails() {{
    if "$@"; then
        printf 'unexpectedly succeeded: %s\\n' "$*" >&2
        return 1
    fi
}}
site_untouched() {{
    test "$CCC_CONFIG" = /elsewhere/site.toml
    if grep -q 'CCC_CONFIG' "$err"; then
        cat "$err" >&2
        return 1
    fi
}}
export CCC_CONFIG=/elsewhere/site.toml
CCC_AGENTS_CONFIG=prior
ccc-use single only 2>"$err"; site_untouched
test "$CCC_AGENTS_CONFIG" = {only}
ccc-use off 2>"$err"; site_untouched
test -z "${{CCC_AGENTS_CONFIG+x}}"
status=$(ccc-use 2>"$err"); site_untouched
grep -qx 'current: (default)' <<<"$status"
ccc-use single 2>"$err"; site_untouched
test "$CCC_AGENTS_CONFIG" = {only}
CCC_AGENTS_CONFIG=prior
fails ccc-use '*' 2>"$err"; site_untouched
grep -q 'unknown variant' "$err"
test "$CCC_AGENTS_CONFIG" = prior
fails ccc-use multi 2>"$err"; site_untouched
test "$CCC_AGENTS_CONFIG" = prior
grep -qF 'multi has 2 preferences: a b space' "$err"
fails ccc-use unknown 2>"$err"; site_untouched
test "$CCC_AGENTS_CONFIG" = prior
fails ccc-use single missing 2>"$err"; site_untouched
test "$CCC_AGENTS_CONFIG" = prior
fails ccc-use single extra args 2>"$err"; site_untouched
test "$CCC_AGENTS_CONFIG" = prior
status=$(ccc-use 2>"$err"); site_untouched
grep -qx 'current: prior' <<<"$status"
grep -qx 'configs: {configs}' <<<"$status"
grep -qx 'single only' <<<"$status"
grep -qx 'multi b space' <<<"$status"
COMP_WORDS=(ccc-use '')
COMP_CWORD=1
_ccc_use || true
printf '%s\\n' "${{COMPREPLY[@]}}" | grep -Fx off
printf '%s\\n' "${{COMPREPLY[@]}}" | grep -Fx single
COMP_WORDS=(ccc-use multi '')
COMP_CWORD=2
_ccc_use || true
printf '%s\\n' "${{COMPREPLY[@]}}" | grep -Fx 'b space'
test "$CCC_AGENTS_CONFIG" = prior
test "$CCC_CONFIG" = /elsewhere/site.toml
stale={only}
configs_dir={shlex.quote(str(configs))}
warning="ccc-use: CCC_CONFIG=$stale names a file under $configs_dir, which holds agents configs, not site config; run: unset CCC_CONFIG"
export CCC_CONFIG=$stale
ccc-use single only 2>"$err"
grep -qxF "$warning" "$err"
test "$CCC_CONFIG" = "$stale"
test "$CCC_AGENTS_CONFIG" = {only}
ccc-use off 2>"$err"
grep -qxF "$warning" "$err"
test "$CCC_CONFIG" = "$stale"
test -z "${{CCC_AGENTS_CONFIG+x}}"
status=$(ccc-use 2>"$err")
grep -qxF "$warning" "$err"
grep -qx 'current: (default)' <<<"$status"
sibling={shlex.quote(str(configs) + "-old/site.toml")}
export CCC_CONFIG=$sibling
ccc-use single only 2>"$err"
fails grep -q 'CCC_CONFIG' "$err"
test "$CCC_CONFIG" = "$sibling"
echo switcher-ok
"""
    completed = bash_runner(command, env)
    assert completed.returncode == 0, completed.stderr
    assert completed.stdout.endswith("switcher-ok\n"), completed.stdout


