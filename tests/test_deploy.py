def test_preferences_lstat_permission_error_is_non_mutating(
    deploy_root, tmp_path, monkeypatch, capsys
):
    config = _config_with_pref(tmp_path)
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path))
    deploy(deploy_root.path)
    prefs = config / "prefs"
    before = _tree(config)
    real_lstat = os.lstat

    def denied(path):
        if path == prefs:
            raise PermissionError(errno.EACCES, "Permission denied", str(prefs))
        return real_lstat(path)

    monkeypatch.setattr(os, "lstat", denied)
    with pytest.raises(PermissionError, match="Permission denied"):
        deploy(deploy_root.path)

    assert _tree(config) == before
    assert "no preference files" not in capsys.readouterr().err


