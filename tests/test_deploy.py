def test_deploy_composes_all_variants_and_uses_parsed_name(deploy_root, tmp_path, monkeypatch, capsys):
    config = tmp_path / "ccc"
    (config / "prefs").mkdir(parents=True)
    preference = PREF
    (config / "prefs" / "default.toml").write_text(preference, encoding="utf-8")
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path))

    result = deploy(deploy_root.path)

    assert [variant.name for variant, _ in result.variants] == ["first", "renamed"]
    assert result.config_count == 2
    generated = config / "configs" / "renamed" / "default.toml"
    assert generated.read_text(encoding="utf-8").endswith(preference)
    assert f'agents_dir = "{config / "agents" / "renamed"}"' in generated.read_text()
    parsed = tomllib.loads(generated.read_text(encoding="utf-8"))
    assert parsed["agents_dir"] == str((config / "agents" / "renamed").resolve())
    assert parsed["agents"]["explorer"]["effort"] == "low"
    assert generated.read_text(encoding="utf-8").startswith(
        f"# agents config generated by agentgen deploy from {config / 'prefs' / 'default.toml'}; "
        "edit that file, not this one; selected through CCC_AGENTS_CONFIG by ccc-use\n"
    )
    assert "no preference files" not in capsys.readouterr().err


def _tree(root: Path) -> tuple[set[Path], dict[Path, bytes]]:
    paths = {path.relative_to(root) for path in root.rglob("*")}
    files = {
        path.relative_to(root): path.read_bytes()
        for path in root.rglob("*")
        if path.is_file()
    }
    return paths, files


def _config_with_pref(tmp_path: Path, text: str = PREF) -> Path:
    config = tmp_path / "ccc"
    (config / "prefs").mkdir(parents=True)
    (config / "prefs" / "default.toml").write_text(text, encoding="utf-8")
    return config


def _assert_no_preferences_warning(err: str, config: Path) -> None:
    q = shlex.quote
    assert f"no preference files in {config / 'prefs'};" in err
    assert "If this deployment succeeds" in err
    assert f"previously generated configs under {config / 'configs'} are removed" in err
    assert "built-in defaults" not in err
    assert "CCC_AGENTS_CONFIG naming a nonexistent file" in err
    assert "ccc refuses to run (exit 2) until that shell runs `ccc-use off`" in err
    assert "or preferences are restored and redeployed" in err
    assert (
        f"Your preference files, {config / 'config.toml'} and {config / 'agents.toml'} "
        "are not touched"
    ) in err
    assert (
        f"mkdir -p {q(str(config / 'prefs'))} && cp "
        f"{q(str(config / 'agents.toml'))} {q(str(config / 'prefs' / 'default.toml'))}\n"
        "then delete its agents_dir line."
    ) in err
    assert f"If {config / 'agents.toml'} does not exist, write {config / 'prefs' / 'default.toml'} by hand" in err
    assert "A preference file holds only default_harness and [agents.*]." in err


